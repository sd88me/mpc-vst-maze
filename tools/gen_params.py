#!/usr/bin/env python3
"""Generate plugins/<name>/src/params_gen.h from the frozen released table (params.json) and params.lock.

Usage: tools/gen_params.py <plugin dir> [...]

Fails if params.json and params.lock disagree on the order (index = VST parameter number = skin binding).
The 1.x popup "open" flags (<key>__open) become: the FIRST one -> "ui_open" (0 = closed, k = list k open, in the
order the flags appear), the others -> inert reserved slots, so nothing after them moves. Parameters added after
the released ones go in <plugin dir>/params_new.json (a list of entries like params.json's) and are appended.
"""
import json, os, sys

K_CHOICE, K_MOMENTARY, K_STEP, K_RUN, K_UIOPEN, K_RESERVED, K_INT, K_HIDDEN = 1, 2, 4, 8, 16, 32, 64, 128


def c(s):
    return json.dumps(s)


def gen(d):
    m = json.load(open(os.path.join(d, "params.json")))
    params = list(m["params"])
    new = os.path.join(d, "params_new.json")
    if os.path.exists(new):
        params += json.load(open(new))
    lock = [l.strip() for l in open(os.path.join(d, "params.lock")) if l.strip()]
    keys = [p["key"] for p in params]
    if keys[:len(lock)] != lock:
        bad = next(i for i, (a, b) in enumerate(zip(keys, lock)) if a != b) if len(keys) >= len(lock) else len(keys)
        sys.exit(f"{d}: parameter order differs from params.lock at index {bad}")
    if len(keys) > len(lock):   # appended parameters join the lock
        with open(os.path.join(d, "params.lock"), "a") as f:
            f.write("".join(k + "\n" for k in keys[len(lock):]))

    popups = [i for i, p in enumerate(params) if p.get("popup_of", -1) >= 0]
    rows, opts = [], []
    for i, p in enumerate(params):
        key, name, unit = p["key"], p["name"], p["unit"]
        flags, choices = 0, p["opts"] or []
        lo, hi = float(p["min"]), float(p["max"])
        if p.get("popup_of", -1) >= 0:
            if i == popups[0]:
                key, name, unit = "ui_open", "List Open", ""
                choices = ["Closed"] + [params[params[j]["popup_of"]]["name"] for j in popups]
                flags = K_CHOICE | K_UIOPEN | K_HIDDEN
            else:
                key, name, unit = f"reserved_{i}", "Reserved", ""
                choices = ["-", "-"]
                flags = K_CHOICE | K_RESERVED | K_HIDDEN
            lo, hi, df = 0.0, len(choices) - 1.0, 0.0
        elif p["nopts"]:
            flags |= K_CHOICE
            lo, hi = 0.0, p["nopts"] - 1.0
            df = float(round(p["def"] * (p["nopts"] - 1)))
        else:
            df = lo + (hi - lo) * p["def"]
            if p.get("int_display"):
                flags |= K_INT
                df = float(round(df))
        if p.get("momentary"):
            flags |= K_MOMENTARY
        if key.startswith(("s1_step", "s2_step")) and len(key) == 8:
            flags |= K_STEP
        if key in ("s1_run", "s2_run"):
            flags |= K_RUN
        if p.get("hidden"):
            flags |= K_HIDDEN
        oname = "nullptr"
        if choices and flags & K_CHOICE:
            oname = f"kOpts{i}"
            opts.append(f"static const char* const {oname}[] = {{{', '.join(c(o) for o in choices)}}};")
        rows.append(f"    {{{c(key)}, {c(name)}, {c(unit)}, {lo!r}f, {hi!r}f, {df!r}f, {len(choices) if flags & K_CHOICE else 0}, "
                    f"{oname}, {flags}, {p.get('debounce_ms', 0)}, {p.get('popup_of', -1)}}},")
    cc = m.get("cc", [])
    out = [
        "// generated by tools/gen_params.py from params.json + params.lock: do not edit",
        "#pragma once",
        f"enum {{ kChoice = {K_CHOICE}, kMomentary = {K_MOMENTARY}, kStep = {K_STEP}, kRun = {K_RUN}, kUiOpen = {K_UIOPEN}, "
        f"kReserved = {K_RESERVED}, kInt = {K_INT}, kHidden = {K_HIDDEN} }};",
        "struct PSpec { const char* key; const char* name; const char* unit; float min, max, def; int nchoices; "
        "const char* const* choices; int flags; int debounceMs; int popupOf; };",
        *opts,
        f"static const int kNumParams = {len(rows)};",
        "static const PSpec g_pspecs[] = {",
        *rows,
        "};",
        f"static const int kCcMap[16] = {{{', '.join(str(x) for x in (cc + [-1] * 16)[:16])}}};   // CC 20..35 -> parameter (1.x HAS_CC_MAP)",
        f"#define PLUG_HAS_NRPN {1 if m.get('nrpn') else 0}",
        f"#define PLUG_UID_STR {c(m['uid'])}",
        f"#define PLUG_NAME_STR {c(m['name'])}",
        "",
    ]
    os.makedirs(os.path.join(d, "src"), exist_ok=True)
    path = os.path.join(d, "src", "params_gen.h")
    text = "\n".join(out)
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)
    print(f"{path}: {len(rows)} params")


if __name__ == "__main__":
    for d in sys.argv[1:]:
        gen(d)
